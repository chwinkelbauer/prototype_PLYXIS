"""Explainability from first principles (no language model involved).

For any asset and decision the planner can answer *why*:

    dL/du = sum_k dTerm_k/du  +  sum_c lambda_c * dh_c/du

i.e. the marginal value of the decision decomposed into the objective terms
(oil sales, power, trucking, emissions, ...) and the priced constraints
(bottlenecks, with their shadow prices). Texts are generated by deterministic
templates from these numbers.
"""
from __future__ import annotations

import math
from typing import Optional

import torch

from ..lang import units as U
from .problem import Problem

KIND_LABEL = {"revenue": "revenue", "cost": "cost", "emission": "emissions"}


def _label(prog, gid: str, li: int) -> str:
    g = prog.gmap[gid]
    if g.is_env:
        return "site-wide"
    inst = prog.flat.instances[g.inst_ids[li]]
    return inst.label or inst.path


def _pretty_con(name: str) -> str:
    n = name.replace("_", " ").replace(".lo", " (min)").replace(".hi", " (max)")
    return n


def components(problem: Problem, x: torch.Tensor, lam: dict, relax: bool = False):
    """Scalar components (in currency) of the Lagrangian for explanation, differentiable in x."""
    e = problem.evaluate(x, relax=relax)
    prog = problem.prog
    comps, names = [], []
    cprice = float(problem.E.get("carbon_price", prog.E0.get("carbon_price", 0.0))) \
        if not isinstance(problem.E.get("carbon_price"), torch.Tensor) else 0.0
    by_name: dict = {}
    for tr in prog.terms:
        if tr.kind == "metric":
            continue
        if tr.final:
            v = e.raw[f"F_{tr.gid}_{_ident(tr.key)}"].sum()
        else:
            xx = e.raw[prog.node_var(tr.gid, tr.key)]
            v = xx.sum() * problem.dt * (problem.T if xx.dim() == 3 and xx.shape[-1] == 1 else 1)
        sign = 1.0 if tr.kind == "revenue" else (-cprice if tr.kind == "emission" else -1.0)
        key = (tr.kind, tr.name)
        by_name[key] = by_name.get(key, 0.0) + sign * v
    for (kind, name), v in by_name.items():
        comps.append(v)
        names.append({"kind": kind, "name": name, "label": f"{name.replace('_', ' ')} ({KIND_LABEL.get(kind, kind)})"})
    for key, h in e.resid.items():
        l = lam.get(key)
        if l is None or float(l.abs().max()) < 1e-9:
            continue
        gid, ck = key
        hh = h if h.dim() == 3 else h.unsqueeze(-1)
        ll = l if l.dim() == 3 else l.unsqueeze(-1)
        per_inst = -(ll * hh).sum(dim=(0, 2)) * problem.J_scale
        for li in range(per_inst.shape[0]):
            if float(ll[:, li].abs().max()) < 1e-9:
                continue
            comps.append(per_inst[li])
            names.append({"kind": "constraint", "name": ck.split(":", 1)[1], "gid": gid, "li": li,
                          "label": f"{_label(prog, gid, li)} - {_pretty_con(ck.split(':', 1)[1])}"})
    soft = e.totals.get("soft_penalty", 0.0)
    if isinstance(soft, torch.Tensor):
        comps.append(-soft.sum())
        names.append({"kind": "penalty", "name": "soft", "label": "permit / soft limits"})
    return torch.stack([c if isinstance(c, torch.Tensor) else torch.tensor(float(c)) for c in comps]), names, e


def explain_instance(problem: Problem, x: torch.Tensor, lam: dict, inst_id: int, max_drivers: int = 5) -> dict:
    prog, sp = problem.prog, problem.space
    gid, li = prog.inst_group[inst_id]
    g = prog.gmap[gid]
    inst = prog.flat.instances[inst_id]
    xx = x.detach().clone().requires_grad_(True)
    comps, names, e = components(problem, xx, lam)
    K = comps.shape[0]
    try:
        jac = torch.autograd.grad(comps, xx, grad_outputs=torch.eye(K), is_grads_batched=True)[0][:, 0, :]
    except Exception:  # noqa: BLE001 - fall back to K backward passes
        rows = []
        for k in range(K):
            gk, = torch.autograd.grad(comps[k], xx, retain_graph=True)
            rows.append(gk[0])
        jac = torch.stack(rows)
    bnd = sp.bounds()
    out = {"asset": inst.path, "label": inst.label or inst.path, "type": inst.type.short, "decisions": []}
    for b in sp.blocks:
        if b.gid != gid:
            continue
        lo, hi, _ = bnd[(b.gid, b.name)]
        lo_v, hi_v = float(lo.reshape(-1)[li if lo.numel() > 1 else 0]), float(hi.reshape(-1)[li if hi.numel() > 1 else 0])
        info = g.ir.decisions[b.name]
        unit = info.unit
        blocks = []
        for h in range(b.H):
            j = b.offset + li * b.H + h
            u = float(x[0, j])
            val = lo_v + (hi_v - lo_v) * u
            if b.domain in ("int", "bool"):
                val = round(val)
            grads = jac[:, j]                                   # $ per unit u over the block
            dur = b.hold * problem.dt
            per10 = grads * 0.1 / max(dur, 1e-9)                # $/h for +10 % of the range
            order = torch.argsort(per10.abs(), descending=True)
            drivers = []
            for k in order[:max_drivers].tolist():
                if abs(float(per10[k])) < 0.5:
                    continue
                drivers.append({**{kk: vv for kk, vv in names[k].items() if kk in ("kind", "name", "label")},
                                "usd_per_h": round(float(per10[k]), 1)})
            net = float(per10.sum())
            at = "max" if u > 0.985 else ("min" if u < 0.015 else None)
            blocks.append({"block": h, "t_start": h * dur, "t_end": min((h + 1) * dur, problem.T * problem.dt),
                           "value": val, "display": _fmt(val, unit, lo_v, hi_v, b.domain), "at_bound": at,
                           "net_usd_per_h": round(net, 1), "drivers": drivers,
                           "summary": _summary(b.name, val, unit, lo_v, hi_v, b.domain, at, drivers, net)})
        out["decisions"].append({"name": b.name, "domain": b.domain, "unit": unit, "blocks": blocks})
    return out


def _fmt(v: float, unit: Optional[str], lo: float, hi: float, domain: str) -> str:
    if domain == "bool":
        return "on" if v >= 0.5 else "off"
    if domain == "int":
        return f"{int(round(v))}"
    if unit:
        try:
            return f"{U.from_canonical(v, unit):,.0f} {unit}"
        except Exception:  # noqa: BLE001
            pass
    if 0.0 <= lo and hi <= 1.0 + 1e-9:
        return f"{v * 100:.0f} %"
    return f"{v:,.2f}"


def _summary(name, val, unit, lo, hi, domain, at, drivers, net) -> str:
    disp = _fmt(val, unit, lo, hi, domain)
    nm = name.replace("_", " ")
    pos = [d for d in drivers if d["usd_per_h"] > 0]
    neg = [d for d in drivers if d["usd_per_h"] < 0]

    def lst(ds):
        return ", ".join(f"{d['label']} {'+' if d['usd_per_h'] > 0 else '-'}${abs(d['usd_per_h']):,.0f}/h" for d in ds[:2])
    if domain == "bool":
        label = "Running" if nm in ("on", "run", "running") else f"{nm.capitalize()} {disp}"
        if val >= 0.5:
            return f"{label}: running pays - {lst(pos) or 'value exceeds cost'}."
        label = "Stopped" if nm in ("on", "run", "running") else f"{nm.capitalize()} {disp}"
        return f"{label}: stopping is better - {lst(neg) or 'cost exceeds value'}."
    if at == "max":
        return f"{nm.capitalize()} at maximum ({disp}): more would still pay ({lst(pos) or 'positive margin'})."
    if at == "min":
        return f"{nm.capitalize()} at minimum ({disp}): {lst(neg) or 'costs exceed value'}."
    if pos and neg:
        return (f"{nm.capitalize()} set to {disp} where gains ({lst(pos)}) balance "
                f"costs ({lst(neg)}).")
    return f"{nm.capitalize()} set to {disp}."


def bottlenecks(problem: Problem, lam: dict, x: Optional[torch.Tensor] = None, top: int = 12) -> list:
    """Binding constraints with their shadow prices and debottlenecking value."""
    prog = problem.prog
    out = []
    for key, l in lam.items():
        gid, ck = key
        s = problem.con_scale.get(key)
        if s is None:
            continue
        l = l if l.dim() == 3 else l.unsqueeze(-1)
        g = prog.gmap[gid]
        ci = g.ir.cons.get(ck)
        for li in range(l.shape[1]):
            row = l[0, li]
            if float(row.max()) < 1e-6:
                continue
            sc = float(s.reshape(-1)[li if s.numel() > 1 else 0])
            price_step = row * problem.J_scale / max(sc, 1e-12)        # $ per canonical unit, per step
            hours = float((row > 1e-6).float().sum()) * problem.dt
            # value of +10 % capacity over the horizon, expressed per day
            v10 = float((price_step * 0.1 * sc).sum()) * 24.0 / (problem.T * problem.dt)
            unit = _rhs_unit(g, ci)
            disp_price = None
            if unit:
                try:
                    f = U.parse_unit(unit)[0]
                    per_unit_day = float(price_step.max()) * f * 24.0 / problem.dt
                    disp_price = f"${per_unit_day:,.2f} per {unit} per day"
                except Exception:  # noqa: BLE001
                    pass
            out.append({"asset": _label(prog, gid, li), "constraint": ck.split(":", 1)[1],
                        "label": f"{_label(prog, gid, li)} - {_pretty_con(ck.split(':', 1)[1])}",
                        "hours_binding": round(hours, 1), "value_10pct_per_day": round(v10, 0),
                        "max_price": disp_price, "gid": gid, "li": li,
                        "profile": [round(float(v), 6) for v in row.tolist()]})
    out.sort(key=lambda r: -r["value_10pct_per_day"])
    return out[:top]


def _rhs_unit(g, ci) -> Optional[str]:
    from ..lang.behavior import Ref, Op
    if ci is None:
        return None
    for side in (ci.rhs, ci.lhs):
        e = side
        while isinstance(e, Op) and e.args:
            e = e.args[0]
        if isinstance(e, Ref) and e.kind == "param":
            return g.ir.param_units.get(e.name)
    return None


def _ident(s: str) -> str:
    import re
    return re.sub(r"[^A-Za-z0-9_]", "_", s)
