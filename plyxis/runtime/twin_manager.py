"""Twin manager: the live twin is code.

Sources
  <base files>        engineered model (field.plx ...) - edited by engineers in Twin Studio
  live.plx            generated: `define <env>_live as <env> { contains: <discovered assets> }`
  calibration.plx     generated: `set <env>_live.<asset>.<property> = <estimate>;` from the estimator

Every change is a commit in the TwinRepo. Recompilation keeps the live state
(estimated parameters and states) by asset path.
"""
from __future__ import annotations

import os
import re
import time
from typing import Optional

import torch

from ..data.discovery import Discovery
from ..data.estimation import Estimator, LiveTwin, TagMap
from ..data.repo import TwinRepo
from ..lang import compile_model, check_source
from ..lang import units as U
from ..lang.errors import PlxError
from ..lang.printer import set_line


class TwinManager:
    def __init__(self, base_files: list, env: str, sim: Optional[str], dt_data: float, window: int = 18):
        self.base_env = env
        self.env = f"{env}_live"
        self.sim = sim
        self.dt_data = dt_data
        self.window = window
        self.base_names = [os.path.basename(f) for f in base_files]
        self.base_dir = os.path.dirname(os.path.abspath(base_files[0]))
        files = {}
        for f in base_files:
            with open(f, encoding="utf-8") as fh:
                files[os.path.basename(f)] = fh.read()
        self.discovered: list = []
        # the generated live model sees the same packages as the engineered model
        self.uses = sorted({u for t in files.values() for u in re.findall(r"^\s*use\s+([\w.]+)\s*;", t, re.M)})
        files["live.plx"] = self._live_text()
        files["calibration.plx"] = self._calibration_text({})
        self.repo = TwinRepo(files)
        self.version = 0
        self.model = None
        self.live: Optional[LiveTwin] = None
        self.compile_seconds = 0.0
        self.build()

    # ------------------------------------------------------------------ sources
    def _live_text(self) -> str:
        body = "\n".join(self.discovered) if self.discovered else "    ## (no discovered assets yet)"
        return ("## GENERATED by PLYXIS data integration - assets discovered from live telemetry.\n"
                "## Review like any code change; every edit is versioned.\n"
                + "".join(f"use {u};\n" for u in self.uses)
                + f"\ndefine {self.env} as {self.base_env} {{\n  contains:\n{body}\n}};\n")

    def _calibration_text(self, values: dict) -> str:
        lines = ["## GENERATED by the PLYXIS estimator - calibrated properties (moving-horizon estimation).",
                 "## Values differ from the engineering estimates by more than 1 %."]
        for (path, prop), (v, unit) in sorted(values.items()):
            disp = U.from_canonical(v, unit) if unit else v
            lines.append(set_line(self.env, path, prop, disp, unit))
        return "\n".join(lines) + "\n"

    def sources(self) -> dict:
        return dict(self.repo.files)

    def _paths(self) -> list:
        out = []
        for name in self.repo.files:
            out.append(os.path.join(self.base_dir, name))
        return out

    def _compile(self, files: dict):
        paths = [os.path.join(self.base_dir, n) for n in files]
        srcs = {os.path.join(self.base_dir, n): t for n, t in files.items()}
        return compile_model(paths, env=self.env, sim=self.sim, sources=srcs, physical=True)

    # ------------------------------------------------------------------ build / rebuild
    def build(self) -> None:
        t0 = time.perf_counter()
        old_live = self.live
        self.model = self._compile(self.repo.files)
        self.compile_seconds = time.perf_counter() - t0
        self.version += 1
        live = LiveTwin(self.model, window=self.window)
        if old_live is not None:
            _transfer(old_live, live)
        self.live = live
        self.tags = TagMap(self.model.program, self.model.flat)
        self.estimator = Estimator(self.live, self.tags, self.dt_data)
        known = {i.path for i in self.model.flat.instances}
        if hasattr(self, "discovery"):
            self.discovery.mark_known(list(known), list(self.tags.prefixes))
        else:
            self.discovery = Discovery(self.model.flat.env_type.rules, known, self.tags.prefixes)

    def check(self, files: dict) -> list:
        paths = [os.path.join(self.base_dir, n) for n in files]
        srcs = {os.path.join(self.base_dir, n): t for n, t in files.items()}
        return check_source(paths, sources=srcs, env=self.env)

    def apply_edit(self, files: dict, author: str, message: str, t_sim: float) -> dict:
        """Engineer edit from Twin Studio: compile, commit, hot-swap."""
        merged = dict(self.repo.files)
        merged.update(files)
        try:
            self._compile(merged)
        except PlxError as ex:
            return {"ok": False, "diagnostics": [d.to_dict() for d in ex.diagnostics]}
        c = self.repo.commit(files, message, author, t_sim)
        self.build()
        return {"ok": True, "commit": c.to_dict() if c else None, "version": self.version}

    def apply_discovery(self, proposal, t_sim: float, author: str = "auto: discovery") -> dict:
        self.discovered.append(proposal.code)
        text = self._live_text()
        merged = dict(self.repo.files)
        merged["live.plx"] = text
        try:
            self._compile(merged)
        except PlxError as ex:
            self.discovered.pop()
            proposal.status = "rejected"
            return {"ok": False, "diagnostics": [d.to_dict() for d in ex.diagnostics]}
        c = self.repo.commit({"live.plx": text}, f"tie-in of {', '.join(proposal.assets)} discovered from "
                                                  f"tag {proposal.tag}", author, t_sim)
        proposal.status = "applied"
        self.build()
        return {"ok": True, "commit": c.to_dict() if c else None, "version": self.version}

    def write_calibration(self, t_sim: float, min_rel: float = 0.01) -> Optional[dict]:
        prog, live = self.model.program, self.live
        values = {}
        for g in prog.groups:
            if g.is_env:
                continue
            for pname, decl in g.ir.type.params.items():
                if decl.calibrate is None or pname not in live.P[g.gid]:
                    continue
                cur = live.P[g.gid][pname].reshape(-1)
                base = prog.P0[g.gid][pname].reshape(-1)
                for li, iid in enumerate(g.inst_ids):
                    b = float(base[li])
                    v = float(cur[li])
                    if abs(v - b) > min_rel * max(abs(b), 1e-9):
                        values[(prog.flat.instances[iid].path, pname)] = (v, decl.unit)
        text = self._calibration_text(values)
        if text == self.repo.files.get("calibration.plx"):
            return None
        c = self.repo.commit({"calibration.plx": text}, f"calibration: {len(values)} properties re-estimated "
                                                         f"from telemetry", "auto: estimator", t_sim)
        return c.to_dict() if c else None


def _transfer(old: LiveTwin, new: LiveTwin) -> None:
    """Carry estimated parameters / states across a recompilation, by asset path."""
    op, np_ = old.prog, new.prog
    for g in np_.groups:
        if g.is_env:
            continue
        for li, iid in enumerate(g.inst_ids):
            path = np_.flat.instances[iid].path
            oiid = op.flat.by_path.get(path)
            if oiid is None:
                continue
            ogid, oli = op.inst_group[oiid]
            for k in new.P[g.gid]:
                if k in old.P.get(ogid, {}):
                    new.P[g.gid][k].reshape(-1)[li] = old.P[ogid][k].reshape(-1)[oli]
                    new.prior_P[g.gid][k].reshape(-1)[li] = old.prior_P[ogid][k].reshape(-1)[oli]
            for k in new.S[g.gid]:
                if k in old.S.get(ogid, {}):
                    new.S[g.gid][k].reshape(-1)[li] = old.S[ogid][k].reshape(-1)[oli]
    new.param_history = old.param_history
