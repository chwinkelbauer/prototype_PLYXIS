@dataclass
class Crossing:
    k: int                  # index of the crossing within its plant
    src: str                # plant side: instance path and port
    src_port: str
    dst: str                # master side: instance path and port
    dst_port: str
    resource: str           # qualified resource
    short: str
    srcs: list = field(default_factory=list)      # every (plant instance, port) whose flow ends at dst.dst_port


@dataclass
class Plant:
    name: str
    dt: float               # canonical
    ratio: int              # plant steps per master step
    members: list           # instance ids in the whole model
    crossings: list
    program: object = None
    flat: Optional[FlatModel] = None
    sinks: list = field(default_factory=list)      # crossing k -> (gid, local index) of its sink in the plant program
    slots: list = field(default_factory=list)      # column slot j -> (gid, local index) in the master; last = probe
    simplex: Optional[tuple] = None                # (gid, local index) of the plant's simplex in the master


@dataclass
class Hierarchy:
    model: object           # CompiledModel of the whole twin (reference program, library, flat netlist)
    master: object          # Program of the group without the plants
    master_flat: FlatModel
    plants: dict            # name -> Plant
    k_max: int              # column slots per plant (plus the probe)
    source: str             # the generated PLX of the boundary entities
    found: list = field(default_factory=list)      # what the detector found (empty when the sim declares plants)
    args: dict = field(default_factory=dict)       # compile_hierarchy's arguments (workers compile their own copy)

    @property
    def program(self):
        return self.model.program


def _ident(s: str) -> str:
    return "".join(c if c.isalnum() else "_" for c in s)


def _helper_source(plants: dict, lib, block: int) -> str:
    """PLX of the boundary sinks (one type per resource), the column slots and the simplex of every plant."""
    pkgs = sorted({c.resource.rpartition(".")[0] for p in plants.values() for c in p.crossings} - {""})
    L = ["## generated by plyxis.lang.hierarchy: the boundary of the plants that have their own time step"]
    L += [f"use {pk};" for pk in pkgs]
    L += ["define plx_share as res [t] { rate_unit = \"t/h\"; };"]
    seen = set()
    for p in plants.values():
        for c in p.crossings:
            if c.short in seen:
                continue
            seen.add(c.short)
            rt = lib.resources[c.resource]
            u = f" [USD/{rt.unit}]" if rt.unit else ""
            ru = f" [{rt.rate_unit}]" if rt.rate_unit else ""
            L += [f"define plx_bsink_{_ident(c.short)} as ent {{",
                  "  properties: track = 0;",
                  f"  state: price = 0{u}; target = 0{ru};",
                  f"  nodes: in i <- {c.short};",
                  "  behavior:",
                  f"    flow = i.{c.short};",
                  "    revenue boundary = flow * price;",
                  "    cost boundary_tracking = track * (flow - target) * (flow - target);",
                  "};"]
    for p in plants.values():
        pid = _ident(p.name)
        states, ports, outs = [], [], []
        for c in p.crossings:
            rt = lib.resources[c.resource]
            ru = f" [{rt.rate_unit}]" if rt.rate_unit else ""
            states.append(f"f{c.k} = 0{ru}")
            ports.append(f"out e{c.k} <- {c.short}")
            outs.append(f"    e{c.k}.{c.short} = w * f{c.k};")
        L += [f"define plx_col_{pid} as ent {{",
              "  properties: w_lo = 0; w_hi = 0; share = 1;",
              "  state: " + "; ".join(states + ["cost_h = 0 [USD/h]"]) + ";",
              f"  decision: w in [w_lo, w_hi] default w_lo hold {block};",
              "  nodes: " + "; ".join(ports + ["out sh <- plx_share"]) + ";",
              "  behavior:"] + outs + [
              "    sh.plx_share = w * share * 1 [t/h];",
              f"    cost plant_{pid} = w * cost_h;",
              "};",
              f"define plx_simplex_{pid} as ent {{",
              "  nodes: in i <- plx_share;",
              "  behavior:",
              "    constraint convex: i.plx_share == 1 [t/h];",
              "};"]
    return "\n".join(L) + "\n"


def _subflat(flat: FlatModel, ids: list, dt: float) -> tuple:
    """The netlist of a subset of instances (internal connections kept), at time step dt."""
    sub = FlatModel(flat.lib, flat.env_type)
    sub.env_params, sub.env_units = dict(flat.env_params), dict(flat.env_units)
    sub.env_inputs, sub.env_meta = set(flat.env_inputs), dict(flat.env_meta)
    sub.rules, sub.origin = list(flat.rules), flat.origin
    sub.sim = dataclasses.replace(flat.sim, dt=dt, plants={})
    idmap, portmap = {}, {}
    keep = set(ids)
    for old in sorted(keep):
        inst = flat.instances[old]
        new = dataclasses.replace(inst, id=len(sub.instances), ports={})
        sub.instances.append(new)
        sub.by_path[new.path] = new.id
        idmap[old] = new.id
        for pname, pid in inst.ports.items():
            p = flat.ports[pid]
            q = dataclasses.replace(p, id=len(sub.ports), inst=new.id, edges=[], resources=list(p.resources),
                                    declared=list(p.declared))
            sub.ports.append(q)
            new.ports[pname] = q.id
            portmap[pid] = q.id
    for e in flat.edges:
        s, d = flat.ports[e.src], flat.ports[e.dst]
        if s.inst in keep and d.inst in keep:
            _connect(sub, portmap[e.src], portmap[e.dst], list(e.resources), e.loc, e.label)
    for k, v in flat.inst_groups.items():
        m = [idmap[i] for i in v if i in idmap]
        if m:
            sub.inst_groups[k] = m
    return sub, portmap


def _connect(sub: FlatModel, src: int, dst: int, resources: list, loc=None, label: str = "") -> None:
    e = Edge(id=len(sub.edges), src=src, dst=dst, resources=list(resources), label=label)
    if loc is not None:
        e.loc = loc
    sub.edges.append(e)
    sub.ports[src].edges.append(e.id)
    sub.ports[dst].edges.append(e.id)


def _add_instance(sub: FlatModel, typ, path: str, params: dict, state0: dict, label: str = "") -> Instance:
    lib = sub.lib
    inst = Instance(id=len(sub.instances), path=path, type=typ, params=dict(params), state0=dict(state0),
                    label=label, spec_key=typ.name)
    sub.instances.append(inst)
    sub.by_path[path] = inst.id
    for pname, pdecl in typ.ports.items():
        res = lib.expand_resources(pdecl.resources, typ.package, pdecl.loc)
        port = Port(id=len(sub.ports), inst=inst.id, name=pname, direction=pdecl.direction, declared=list(res),
                    exclusive=pdecl.exclusive, resources=list(res))
        sub.ports.append(port)
        inst.ports[pname] = port.id
    return inst


def plant_crossings(flat: FlatModel, plants: dict) -> dict:
    """Instance ids of each plant (declared groups) and the connections that leave it."""
    owner: dict = {}
    for name in plants:
        for i in flat.inst_groups.get(name, []):
            if i in owner and owner[i] != name:
                raise ValueError(f"'{flat.instances[i].path}' belongs to plants '{owner[i]}' and '{name}'")
            owner[i] = name
    return _crossings(flat, owner, list(plants))


def _crossings(flat: FlatModel, owner: dict, names: list) -> dict:
    """The connections that leave each plant, one crossing per port they end at on the other side (the power of
    fifteen units into one grid connection is one flow at the fence, not fifteen)."""
    out: dict = {name: {} for name in names}
    for e in flat.edges:
        sp, dp = flat.ports[e.src], flat.ports[e.dst]
        a, b = owner.get(sp.inst), owner.get(dp.inst)
        if a == b:
            continue
        si, di = flat.instances[sp.inst], flat.instances[dp.inst]
        if a is None or b is not None:
            what = f"plant '{b}'" if a is None else f"plant '{b}' from plant '{a}'"
            raise ValueError(f"connection into {what}: {si.path}.{sp.name} -> {di.path}.{dp.name}. Put the unit that "
                             f"sends it into the plant's group (every crossing must leave the plant)")
        if len(e.resources) != 1:
            raise ValueError(f"{si.path}.{sp.name} -> {di.path}.{dp.name} carries {len(e.resources)} resources; a "
                             f"plant boundary carries one")
        r = e.resources[0]
        key = (di.path, dp.name, r)
        c = out[a].get(key)
        if c is None:
            c = out[a][key] = Crossing(len(out[a]), si.path, sp.name, di.path, dp.name, r, r.split(".")[-1])
        c.srcs.append((si.path, sp.name))
    return {name: ([i for i, o in owner.items() if o == name], list(out[name].values())) for name in names}


# ----------------------------------------------------------------------------- finding the plants
def static_value(e, params: dict, dt: float, env: Optional[dict] = None):
    """The value of a static IR expression (constants, properties, dt) for one instance, or None."""
    from .behavior import C, Op, Ref
    if isinstance(e, C):
        return float(e.value)
    if isinstance(e, Ref):
        if e.kind == "param":
            v = params.get(e.name)
            return float(v) if isinstance(v, (int, float)) else None
        if e.kind == "b" and e.name == "dt":
            return float(dt)
        if e.kind == "env" and env is not None and isinstance(env.get(e.name), (int, float)):
            return float(env[e.name])
        return None
    if isinstance(e, Op):
        a = [static_value(x, params, dt, env) for x in e.args]
        if any(v is None for v in a):
            return None
        f = {"add": lambda: a[0] + a[1], "sub": lambda: a[0] - a[1], "mul": lambda: a[0] * a[1],
             "div": lambda: a[0] / a[1] if a[1] else None, "neg": lambda: -a[0], "min": lambda: min(a),
             "max": lambda: max(a), "pos": lambda: max(a[0], 0.0), "abs": lambda: abs(a[0])}.get(e.op)
        return f() if f else None
    return None


@dataclass
class Found:
    """A plant the detector found: its members, the step its units need and why."""
    name: str
    dt: float
    members: list                   # instance ids
    seeds: dict                     # instance id -> (step it needs, the duration that sets it)
    joined: dict                    # instance id -> why it joined (a small buffer, a sender into the plant)
    cut: list                       # (instance id, port, why the connection is cut there)
    kind: str = "plant"             # plant (its own step) | region (a regional network at the simulation's step)


def _duration_rules(g) -> list:
    """What a unit's behaviour says about the step it can be planned at: delays given as durations and holds given
    in time. Each rule: (label, function(params, step) -> number of steps it spans at that step)."""
    from .behavior import Op, Ref, walk_refs
    rules = []
    users: dict = {}                     # delay node -> the constraint or state that reads it
    for ck, ci in g.ir.cons.items():
        for kind, name in walk_refs(ci.lhs) | walk_refs(ci.rhs):
            if kind == "node":
                users.setdefault(name, f"constraint {ci.name}")
    for key, node in g.ir.nodes.items():
        if key.startswith("next:"):
            for kind, name in walk_refs(node):
                if kind == "node":
                    users.setdefault(name, f"state {key[5:]}")
    for key, node in g.ir.nodes.items():
        if isinstance(node, Op) and node.op == "delay":
            k = node.extra["k"]
            if isinstance(k, Op) and ("b", "dt") in walk_refs(k):
                rules.append((f"the window of its {users.get(key, key)}", lambda P, s, k=k: static_value(k, P, s)))
    for n, d in g.ir.decisions.items():
        if d.hold_hours is not None:
            rules.append((f"{n} held {d.hold_hours * 60:g} min", lambda P, s, h=d.hold_hours: h / s))
    return rules


def _steps_ok(v) -> bool:
    return v is not None and v >= 1 - 1e-6 and abs(v - round(v)) < 1e-6


def detect_plants(model, buffer_steps: float = 24.0, samples: int = 4, seed: int = 0) -> list:
    """Plants in one twin, found from its equations alone.

    1. Every unit states its durations in time (a heat's tap to tap, how often a set point may change). A step suits
       it when each spans a whole number of steps; the largest such step that divides the simulation's is the step
       the unit needs. Units that need a finer step than the simulation's seed plants.
    2. A plant grows along its connections. It takes in every unit that sends into it (a flow decided outside would
       be an input the plant cannot plan) and every receiver whose buffer is small: a stock that holds less than
       `buffer_steps` simulation steps of the flow through it sees the plant's pattern within the step, not just its
       average (a 1,400 t ladle furnace between converters and casters). A receiver with a large buffer (a slab yard
       of days) or none (a market, a grid connection: units that state nothing finer than the simulation's step) takes
       the flow per simulation step: the connection is cut there and becomes a flow at the plant's fence.
    3. Plants that touch merge; each runs at the largest step all its units accept.

    The flows through the buffers are measured on the twin itself at its simulation step, at the default decisions and
    at a few random ones (`samples`)."""
    import torch
    from ..optim.problem import Problem
    from .behavior import Ref
    prog = model.program
    flat = prog.flat
    master = float(prog.dt)
    cands = [master / n for n in range(1, 721) if master / n >= 1.0 / 60 - 1e-9]
    by_id = {}
    for g in prog.groups:
        if g.is_env:
            continue
        for li, iid in enumerate(g.inst_ids):
            by_id[iid] = (g, li)

    # 1. the step every unit needs
    need, why = {}, {}
    rules_of = {}
    for iid, (g, li) in by_id.items():
        rules = rules_of.setdefault(g.gid, _duration_rules(g))
        if not rules:
            continue
        P = flat.instances[iid].params
        for s in cands:
            bad = [lab for lab, f in rules if not _steps_ok(f(P, s))]
            if not bad:
                need[iid] = s
                break
            why[iid] = bad[0]
        else:
            raise ValueError(f"'{flat.instances[iid].path}': no step down to one minute resolves {why[iid]}")
    seeds = {i: (s, why.get(i, "")) for i, s in need.items() if s < master - 1e-9}
    if not seeds:
        return []

    # flows through every in-port, measured on the twin
    pb = Problem(prog)
    gen = torch.Generator().manual_seed(seed)
    u = torch.cat([pb.space.default_u(1), pb.space.random_u(samples, gen)])
    with torch.no_grad():
        raw = pb.evaluate(u, relax=True).raw

    def in_flow(g, li, port_res):
        try:
            x = raw[prog.node_var(g.gid, f"in:{port_res}")]
        except KeyError:
            return 0.0
        x = x.reshape(x.shape[0], -1, x.shape[-1]) if x.dim() >= 2 else x.reshape(1, 1, -1)
        x = x[:, li if x.shape[1] > 1 else 0]
        return float(x.abs().mean())

    def deps(ir, e, acc, seen):
        for kind, name in __import__("plyxis.lang.behavior", fromlist=["walk_refs"]).walk_refs(e):
            if kind == "in":
                acc.add(name)
            elif kind == "node" and name not in seen and name in ir.nodes:
                seen.add(name)
                deps(ir, ir.nodes[name], acc, seen)
        return acc

    state_ports = {}            # gid -> state -> in-ports ("port:res") its update reads

    def buffer_of(iid, port):
        """(hours of throughput the smallest buffer fed by this port holds, state) or None if no stock is fed."""
        g, li = by_id[iid]
        sp = state_ports.setdefault(g.gid, {s: deps(g.ir, g.ir.nodes[f"next:{s}"], set(), set())
                                            for s, si in g.ir.states.items() if si.has_update
                                            and f"next:{s}" in g.ir.nodes})
        P = flat.instances[iid].params
        best = None
        for s, ports in sp.items():
            if not any(p.split(":")[0] == port for p in ports):
                continue
            si = g.ir.states[s]
            lo = static_value(si.lo, P, master) if si.lo is not None else None
            hi = static_value(si.hi, P, master) if si.hi is not None else None
            rng = (hi - lo) if (hi is not None and lo is not None) else float("inf")
            thr = sum(in_flow(g, li, p) for p in ports)
            hours = rng / thr if thr > 1e-9 else float("inf")
            if best is None or hours < best[0]:
                best = (hours, s)
        return best

    # 2. grow
    inside = set(seeds)
    joined, cut = {}, {}
    parent = {i: i for i in by_id}

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    def union(a, b):
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[max(ra, rb)] = min(ra, rb)

    changed = True
    while changed:
        changed = False
        for e in flat.edges:
            sp_, dp_ = flat.ports[e.src], flat.ports[e.dst]
            u_, v_ = sp_.inst, dp_.inst
            if u_ not in by_id or v_ not in by_id:
                continue
            if u_ in inside and v_ in inside:
                union(u_, v_)
            elif v_ in inside:
                inside.add(u_)
                union(u_, v_)
                joined[u_] = f"sends into {flat.instances[v_].path}.{dp_.name}"
                changed = True
            elif u_ in inside:
                b = buffer_of(v_, dp_.name)
                if b is not None and b[0] < buffer_steps * master:
                    inside.add(v_)
                    union(u_, v_)
                    joined[v_] = (f"its {b[1]} holds {b[0]:.1f} h of its flow (less than {buffer_steps * master:g} h)")
                    changed = True
                else:
                    cut[(v_, dp_.name)] = ("no stock fed by it: takes the flow per simulation step" if b is None else
                                           f"its {b[1]} holds {b[0]:.0f} h of its flow")

    # 3. plants
    comps: dict = {}
    for i in sorted(inside):
        comps.setdefault(find(i), []).append(i)
    found = []
    for k, members in enumerate(sorted(comps.values(), key=lambda m: m[0])):
        mset = set(members)
        for s in cands:
            if all(all(_steps_ok(f(flat.instances[i].params, s)) for _, f in rules_of.get(by_id[i][0].gid, []))
                   for i in members):
                dtp = s
                break
        paths = sorted(flat.instances[i].path for i in members if i in seeds)
        pre = paths[0].split("_")[0]
        name = pre if all(p.split("_")[0] == pre for p in paths) else f"plant{k + 1}"
        first = flat.instances[min((i for i in members if i in seeds), key=lambda i: flat.instances[i].path)]
        name = f"{name}.{first.type.name.split('.')[-1]}"
        found.append(Found(name, dtp, members, {i: seeds[i] for i in members if i in seeds},
                           {i: joined[i] for i in members if i in joined},
                           [(v, p, w) for (v, p), w in cut.items()
                            if any(flat.ports[e.src].inst in mset and flat.ports[e.dst].inst == v
                                   and flat.ports[e.dst].name == p for e in flat.edges)]))
    names = [f.name for f in found]
    for k, f in enumerate(found):
        if names.count(f.name) > 1:
            f.name = f"{f.name}_{k + 1}"
    return found


def _in_deps(ir, e, acc: set, seen: set) -> set:
    from .behavior import walk_refs
    for kind, name in walk_refs(e):
        if kind == "in":
            acc.add(name.split(":")[0])
        elif kind == "node" and name not in seen and name in ir.nodes:
            seen.add(name)
            _in_deps(ir, ir.nodes[name], acc, seen)
    return acc


def detect_regions(model, min_units: int = 3, plants: Optional[list] = None) -> list:
    """Regional networks in one twin, found from its connections alone.

    An exchange is where flows leave the model: a unit that takes flows from at least two units, passes nothing on
    and keeps no stock of them (a bounded state; a contract's backlog is an account) - a market, a grid connection,
    a scrap market. Take every exchange out and the rest falls into connected pieces; an exchange whose
    neighbours all lie in one piece belongs to it (a site's own grid connection, a market only one network serves)
    and goes back in, until nothing changes. What stays out is shared by several networks: the group keeps it. Each
    piece is a regional network - sites tied by their own transfers - and becomes a block at the simulation's step:
    its program is its input-output function at the exchanges it trades with. Pieces without a decision or without a
    connection to a shared exchange stay with the group.

    With `plants` (from `detect_plants`) the plants are blocks of their own: their units are taken out, and the units
    at their fences (a slab yard, a grid connection) stay with the group like a shared exchange - every block then
    trades with the group only, never with another block."""
    prog = model.program
    flat = prog.flat
    by_id = {}
    for g in prog.groups:
        if g.is_env:
            continue
        for li, iid in enumerate(g.inst_ids):
            by_id[iid] = (g, li)
    nbrs = {i: set() for i in by_id}
    senders = {i: set() for i in by_id}
    passes = set()
    for e in flat.edges:
        u, v = flat.ports[e.src].inst, flat.ports[e.dst].inst
        if u in by_id and v in by_id and u != v:
            nbrs[u].add(v)
            nbrs[v].add(u)
            senders[v].add(u)
            passes.add(u)
    stocked: dict = {}

    def stockless(i):
        g = by_id[i][0]
        if g.gid not in stocked:
            ports = set()
            for s, si in g.ir.states.items():
                # a stock has a capacity; an unbounded account (a contract's backlog, a running total) is not one
                if si.has_update and si.hi is not None and f"next:{s}" in g.ir.nodes:
                    ports |= _in_deps(g.ir, g.ir.nodes[f"next:{s}"], set(), set())
            stocked[g.gid] = ports
        return not stocked[g.gid]

    def pieces(out: set) -> dict:
        comp, k = {}, 0
        for i in sorted(by_id):
            if i in out or i in comp:
                continue
            stack = [i]
            comp[i] = k
            while stack:
                a = stack.pop()
                for b in nbrs[a]:
                    if b not in out and b not in comp:
                        comp[b] = k
                        stack.append(b)
            k += 1
        return comp

    inplant = {i for f in (plants or []) for i in f.members}
    fence = {v for f in (plants or []) for v, _, _ in f.cut} - inplant
    shared = {i for i in by_id if len(senders[i]) >= 2 and i not in passes and stockless(i)} | fence
    for _ in range(50):
        comp = pieces(shared | inplant)
        keep = {c for c in shared if c in fence or len({comp[n] for n in nbrs[c] if n in comp}) >= 2}
        if keep == shared:
            break
        shared = keep
    comp = pieces(shared | inplant)
    groups: dict = {}
    for i, k in comp.items():
        groups.setdefault(k, []).append(i)
    found = []
    for k, members in sorted(groups.items(), key=lambda kv: min(kv[1])):
        has_dec = any(by_id[i][0].ir.decisions for i in members)
        touches = sorted({(c, flat.ports[e.dst].name) for i in members for c in nbrs[i] if c in shared
                          for e in flat.edges if flat.ports[e.src].inst == i and flat.ports[e.dst].inst == c})
        if len(members) < min_units or not has_dec or not touches:
            continue
        pre = {}
        for i in members:
            if getattr(flat.instances[i], "line", None) is not None:      # lanes and transfers name no site
                continue
            p = flat.instances[i].path.split("_")[0]
            pre[p] = pre.get(p, 0) + 1
        name = "+".join(sorted(p for p, n in pre.items() if n >= 3)) or \
            (max(sorted(pre), key=lambda p: pre[p]) if pre else f"region{len(found) + 1}")
        cut = [(c, port, "at a plant's fence" if c in fence else
                 f"shared by {len({comp[n] for n in nbrs[c] if n in comp})} regional networks") for c, port in touches]
        found.append(Found(name, float(prog.dt), sorted(members), {}, {}, cut, kind="region"))
    if len(found) < (1 if plants else 2):
        return []
    names = [f.name for f in found]
    for f in found:
        if names.count(f.name) > 1:
            f.name = f"{f.name}{sum(1 for g in found[:found.index(f) + 1] if g.name.startswith(f.name))}"
    return found


def describe(found: list, flat: FlatModel) -> str:
    """The detector's findings in words."""
    L = []
    for f in found:
        if f.kind == "region":
            L.append(f"region {f.name}: {len(f.members)} units at the simulation's {f.dt * 60:g}-minute step")
            for v, p, w in sorted(f.cut, key=lambda c: (flat.instances[c[0]].path, c[1])):
                L.append(f"  trades at {flat.instances[v].path}.{p}: {w}")
            continue
        L.append(f"plant {f.name}: {len(f.members)} units at {f.dt * 60:g}-minute steps")
        for i, (s, w) in sorted(f.seeds.items(), key=lambda kv: flat.instances[kv[0]].path):
            L.append(f"  {flat.instances[i].path}: needs {s * 60:g}-minute steps ({w} spans no whole number of "
                     f"steps at a coarser one)")
        for i, w in sorted(f.joined.items(), key=lambda kv: flat.instances[kv[0]].path):
            L.append(f"  {flat.instances[i].path}: joined - {w}")
        for v, p, w in sorted(f.cut, key=lambda c: (flat.instances[c[0]].path, c[1])):
            L.append(f"  fence at {flat.instances[v].path}.{p}: {w}")
    return "\n".join(L)


def compile_hierarchy(files: list, env: Optional[str] = None, sim: Optional[str] = None,
                      sources: Optional[dict] = None, k_max: int = 6, block: int = 8,
                      buffer_steps: float = 24.0, split: str = "auto") -> Hierarchy:
    """Compile one twin into the master and a program per block. The blocks are found from the equations: plants
    whose units need a finer step and regional networks. `split` = "auto" (the default: the blocks of the asset graph's
    tree, `lang/blocks.py`, that are at their own step - the others are found and reported but coordinating them by
    prices does not pay yet, bench/results/corporate_regions*.json) | "plants" | "regions" | "both" (the earlier
    detectors: `detect_plants`, `detect_regions`, side by side). A simulation's `plants:` section overrides them all."""
    from .compiler import Compiler
    model = compile_model(files, env=env, sim=sim, sources=sources)
    flat, lib, diags = model.flat, model.lib, model.diagnostics
    spec = flat.sim
    T = max(1, int(round(spec.horizon / spec.dt)))
    found, tree = [], None
    if spec.plants:
        steps_of, groups = dict(spec.plants), plant_crossings(flat, spec.plants)
    else:
        if split == "auto":
            # the blocks of the asset graph's tree that the plan uses (lang/blocks.py): those at their own step
            from .blocks import find_structure, used_blocks
            tree = find_structure(model, buffer_steps=buffer_steps)
            for b in used_blocks(tree):
                cut = [(flat.by_path[p], port, "at its fence") for d, p, port, r, n in b.interface if d == "out"]
                found.append(Found(b.name, b.step, list(b.members), {}, {}, cut))
        else:
            found = detect_plants(model, buffer_steps=buffer_steps) if split in ("plants", "both") else []
        if split == "both":
            found = found + detect_regions(model, plants=found)
        elif split == "regions":
            found = detect_regions(model)
        if not found:
            raise ValueError(f"'{spec.name}': no unit needs a finer step than {spec.dt * 60:g} min and no regional "
                             f"networks share exchanges: one program")
        owner = {i: f.name for f in found for i in f.members}
        steps_of, groups = {f.name: f.dt for f in found}, _crossings(flat, owner, [f.name for f in found])
    plants = {}
    for name, (ids, crossings) in groups.items():
        dtp = steps_of[name]
        ratio = spec.dt / dtp
        if dtp <= 0 or abs(ratio - round(ratio)) > 1e-6 or round(ratio) < 1:
            raise ValueError(f"plant '{name}': its step must divide the simulation's step ({spec.dt} / {dtp})")
        if not crossings:
            raise ValueError(f"plant '{name}' has no connection to the rest of the group")
        plants[name] = Plant(name, dtp, int(round(ratio)), ids, crossings)
    src = _helper_source(plants, lib, max(1, min(block, T)))
    lib.add_program(parse(src, "<plx-hierarchy>", diags), ".")
    diags.raise_if_errors()

    # every plant: its own instances plus a priced sink at the end of each connection that leaves it
    for p in plants.values():
        sub, portmap = _subflat(flat, p.members, p.dt)
        for c in p.crossings:
            typ = lib.get_type(f"plx_bsink_{_ident(c.short)}")
            s = _add_instance(sub, typ, f"PLX_BND_{_ident(p.name)}_{c.k}", {"track": 0.0},
                              {"price": 0.0, "target": 0.0}, label=f"{c.src} -> {c.dst}")
            for sp_path, sp_name in (c.srcs or [(c.src, c.src_port)]):
                src_port = sub.ports[sub.instances[sub.by_path[sp_path]].ports[sp_name]].id
                _connect(sub, src_port, s.ports["i"], [c.resource], label="plant boundary")
        diags.raise_if_errors()
        p.flat = sub
        p.program = Compiler(sub, diags, physical=False).compile()
        p.sinks = [p.program.inst_group[sub.by_path[f"PLX_BND_{_ident(p.name)}_{c.k}"]] for c in p.crossings]

    # the master: everything else, every plant as an envelope of column slots + its simplex
    rest = [i.id for i in flat.instances if not any(i.id in set(p.members) for p in plants.values())]
    master, portmap = _subflat(flat, rest, spec.dt)
    for p in plants.values():
        pid = _ident(p.name)
        ctyp, styp = lib.get_type(f"plx_col_{pid}"), lib.get_type(f"plx_simplex_{pid}")
        simplex = _add_instance(master, styp, f"PLX_SIMPLEX_{pid}", {}, {}, label=f"{p.name} column weights")
        st0 = {f"f{c.k}": 0.0 for c in p.crossings}
        st0["cost_h"] = 0.0
        for j in range(k_max + 1):
            probe = j == k_max
            col = _add_instance(master, ctyp, f"PLX_COL_{pid}_{j}",
                                {"w_lo": 1.0 if probe else 0.0, "w_hi": 1.0 if probe else 0.0,
                                 "share": 0.0 if probe else 1.0}, dict(st0),
                                label=f"{p.name} {'probe' if probe else f'schedule {j}'}")
            for c in p.crossings:
                dst = master.instances[master.by_path[c.dst]]
                _connect(master, col.ports[f"e{c.k}"], dst.ports[c.dst_port], [c.resource], label="plant boundary")
            _connect(master, col.ports["sh"], simplex.ports["i"], ["plx_share"])
    diags.raise_if_errors()
    mprog = Compiler(master, diags, physical=False).compile()
    for p in plants.values():
        pid = _ident(p.name)
        p.slots = [mprog.inst_group[master.by_path[f"PLX_COL_{pid}_{j}"]] for j in range(k_max + 1)]
        p.simplex = mprog.inst_group[master.by_path[f"PLX_SIMPLEX_{pid}"]]
    h = Hierarchy(model, mprog, master, plants, k_max, src, found,
                  dict(files=list(files), env=env, sim=sim, sources=sources, k_max=k_max, block=block,
                       buffer_steps=buffer_steps, split=split))
    h.tree = tree
    return h


def steps(program) -> int:
    return max(1, int(round(program.horizon / program.dt)))


