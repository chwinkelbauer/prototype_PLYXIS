"""Plants with their own time step inside one model: split, boundaries, column slots.

A simulation can name plants - instance groups of the environment - and give each its own time step:

    define DE as group { DE_*, L_DE_*, T_DE_*, T_NL_DE, T_FR_DE };     # after the instances
    define corp96 as sim { env: aquila; horizon = 96 [h]; step = 1 [h];
      plants: DE = 15 [min]; };

The model stays one twin: one register, one calibration, one set of equations. `compile_hierarchy` compiles it
once as a whole (the reference program) and then splits its netlist:

* every plant becomes a program of its own at its time step. Each connection that leaves the plant ends in a
  boundary sink that prices the flow: revenue = flow x price, the price being the group's shadow price of that
  flow in that hour (`boundary`); a tracking term can hold the flow near a target (`boundary_tracking`). That
  program is the plant's input-output function: given prices for what crosses its fence, the best schedule of
  every unit inside it;
* the rest of the group becomes the master program at the simulation's step. Each plant appears in it as an
  envelope of column slots: a slot holds one schedule of the plant - its boundary flows and its internal value,
  hour by hour - and a weight per block of `block` steps; in every hour the weights of a plant add up to one
  (Dantzig-Wolfe, convexified per block). One more slot, the
  probe, carries no schedule and always weight one: the derivative of the master's Lagrangian with respect to
  its flows is the price vector the plant is solved against. The connections end where the plant's did.

The solver that alternates the two is `plyxis/optim/corporate.py`. A connection into a plant from outside it is
not supported yet: put the unit that sends it (a transfer lane, say) into the plant's group, then every
crossing leaves the plant.
"""
