"""Generate the synthetic *Kestrel Field* asset register (deterministic, seed 42).

Outputs (next to this file):
  wells.csv   - engineering estimates the twin starts from (what an operator has in its systems)
  pads.csv    - multi-well pads with their two candidate tank batteries
  truth.plx   - HIDDEN ground truth for the plant emulator: true well performance, worn pumps,
                and one new well that is not in the asset register yet (tie-in during the demo)

All data is synthetic. The field is placed in a sparsely developed part of the Delaware Basin
(West Texas) purely for realistic map context.
"""
from __future__ import annotations

import csv
import math
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
SEED = 42

FACILITIES = {
    "CTB_N": (31.6750, -103.7000),
    "CTB_C": (31.6100, -103.6650),
    "CTB_S": (31.5450, -103.7050),
}


def offset(lat: float, lon: float, north_km: float, east_km: float) -> tuple:
    return (lat + north_km / 110.574, lon + east_km / (111.320 * math.cos(math.radians(lat))))


def dist_km(a, b) -> float:
    dn = (a[0] - b[0]) * 110.574
    de = (a[1] - b[1]) * 111.320 * math.cos(math.radians(a[0]))
    return math.hypot(dn, de)


def main() -> None:
    rng = random.Random(SEED)
    pads = []
    pad_no = 0
    for ctb, n_pads, bearing0 in (("CTB_N", 4, 20), ("CTB_C", 4, 200), ("CTB_S", 4, 120)):
        for k in range(n_pads):
            pad_no += 1
            ang = math.radians(bearing0 + k * 360 / n_pads + rng.uniform(-25, 25))
            r = rng.uniform(2.4, 5.8)
            lat, lon = offset(*FACILITIES[ctb], r * math.cos(ang), r * math.sin(ang))
            name = f"PAD{pad_no:02d}"
            ranked = sorted(FACILITIES, key=lambda c: dist_km((lat, lon), FACILITIES[c]))
            home = ctb
            alt = ranked[0] if ranked[0] != home else ranked[1]
            pads.append(dict(name=name, label=f"PAD-{pad_no:02d}", lat=round(lat, 5), lon=round(lon, 5),
                             home=home, alt=alt, tag=f"KST.P{pad_no:02d}"))

    wells, truth = [], []
    for p in pads:
        n = rng.randint(6, 10)
        az = rng.uniform(0, 180)
        for j in range(1, n + 1):
            d = (j - (n + 1) / 2) * 0.045
            lat, lon = offset(p["lat"], p["lon"], d * math.cos(math.radians(az)), d * math.sin(math.radians(az)))
            q = min(2600.0, max(150.0, math.exp(rng.gauss(math.log(640), 0.5))))
            wc = round(rng.uniform(0.55, 0.85), 3)
            gor = min(6.0, max(0.4, math.exp(rng.gauss(math.log(1.7), 0.55))))
            if p["home"] == "CTB_S" and rng.random() < 0.4:
                gor *= 1.8                                    # gassier southern acreage
            health = round(1 - (rng.random() ** 3) * 0.55, 3)
            kw = round(40 + 0.09 * q, 1)
            pn = int(p["name"][3:])
            name = f"P{pn:02d}_W{j:02d}"
            wells.append(dict(name=name, label=f"PAD-{pn:02d} W-{j:02d}", pad=p["name"], lat=round(lat, 6),
                              lon=round(lon, 6), q_max=round(q, 1), wc=wc, gor=round(gor, 3), kw_rated=kw,
                              health=health, tag=f"KST.P{pn:02d}.W{j:02d}"))
            # hidden truth: engineering estimates are off by a realistic margin
            tq = q * math.exp(rng.gauss(0, 0.14))
            twc = min(0.97, max(0.3, wc + rng.gauss(0.015, 0.04)))
            tgor = gor * math.exp(rng.gauss(0.03, 0.16))
            th = max(0.25, min(1.0, health - abs(rng.gauss(0.04, 0.05))))
            truth.append((name, tq, twc, tgor, th))

    # three pumps degrade fast in reality (failures the twin must anticipate from vibration)
    fast_wear = rng.sample([w["name"] for w in wells if w["q_max"] > 700], 3)

    with open(os.path.join(HERE, "pads.csv"), "w", newline="", encoding="utf-8") as fh:
        wr = csv.DictWriter(fh, fieldnames=list(pads[0]))
        wr.writeheader()
        wr.writerows(pads)
    with open(os.path.join(HERE, "wells.csv"), "w", newline="", encoding="utf-8") as fh:
        wr = csv.DictWriter(fh, fieldnames=list(wells[0]))
        wr.writeheader()
        wr.writerows(wells)

    new_pad = pads[6]
    nlat, nlon = offset(new_pad["lat"], new_pad["lon"], 0.31, 0.12)
    lines = [
        "## HIDDEN GROUND TRUTH - used only by the plant emulator, never by the twin.",
        "## Generated by generate.py (seed 42). Synthetic data.",
        "use oilgas;",
        "",
        "## The real field = the registered field + a new well that is being tied in.",
        "define kestrel_truth as kestrel {",
        "  contains:",
        f"    init P07_W11 as esp_well {{ q_max = 1480 [bbl/d]; wc = 0.52; gor = 1.9 [Mscf/bbl]; "
        f"kw_rated = 175 [kW]; up = 0; at = ({nlat:.6f}, {nlon:.6f}); tag = \"KST.P07.W11\"; "
        f"label = \"PAD-07 W-11\"; }};",
        "    connect(P07_W11.prod, PAD07.wells);",
        "};",
        "",
    ]
    for name, tq, twc, tgor, th in truth:
        lines.append(f"set kestrel_truth.{name}.q_max = {tq:.1f} [bbl/d];")
        lines.append(f"set kestrel_truth.{name}.wc = {twc:.3f};")
        lines.append(f"set kestrel_truth.{name}.gor = {tgor:.3f} [Mscf/bbl];")
        lines.append(f"set kestrel_truth.{name}.health = {th:.3f};")
    for name in fast_wear:
        lines.append(f"set kestrel_truth.{name}.wear_rate = 0.0065 [1/h];   ## failing pump")
    lines.append("set kestrel_truth.SWD2.inj_cap = 21000 [bbl/d];")
    lines.append("set kestrel_truth.CTB_C.liq_cap = 27500 [bbl/d];")
    with open(os.path.join(HERE, "truth.plx"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    tot_q = sum(w["q_max"] for w in wells)
    oil = sum(w["q_max"] * 0.85 * (1 - w["wc"]) for w in wells)
    gas = sum(w["q_max"] * 0.85 * (1 - w["wc"]) * w["gor"] for w in wells)
    print(f"{len(pads)} pads, {len(wells)} wells, nominal liquid {tot_q * 0.85:,.0f} bbl/d, "
          f"oil {oil:,.0f} bbl/d, gas {gas:,.0f} Mscf/d; fast-wear pumps: {fast_wear}")


if __name__ == "__main__":
    main()
