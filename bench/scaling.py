"""Scaling benchmark: an operator with N Kestrel-sized fields sharing a regional gas plant,
a crude terminal and a company-wide flaring allowance (multi-site coupling).

The enterprise twin is plain PLX: the whole portfolio is one generate loop.

    python -m bench.scaling --fields 1 2 4 8
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time

import torch

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from plyxis.lang import compile_model  # noqa: E402
from plyxis.optim import metaheur as MH  # noqa: E402
from plyxis.optim.cascade import Cascade, CascadeConfig  # noqa: E402
from plyxis.optim.problem import Problem  # noqa: E402

TEMPLATE = r'''## =====================================================================================
##  ENTERPRISE - {N} Kestrel-sized fields operated as one system (generated by bench/scaling.py)
##  Shared regional gas plant and crude terminal, company-wide flaring allowance.
## =====================================================================================
use oilgas;

define enterprise as env {{
  origin = (31.80, -103.30);
  properties:
    oil_price    = 72.0  [USD/bbl]  input;
    gas_price    = 1.20  [USD/Mscf] input;
    power_price  = 0.055 [USD/kWh]  input;
    grid_co2     = 0.38  [kgCO2e/kWh];
    carbon_price = 60    [USD/tCO2e];
    flare_permit = {permit} [Mscf/d];
  contains:
    init GASPLANT as gas_sales {{ at = (31.70, -103.10); label = "Regional gas plant"; cap = {plant_cap} [Mscf/d]; }};
    init LACT as oil_sales {{ at = (31.72, -103.12); label = "Regional crude terminal"; }};
    for k in 1..{N} {{
      dy = 0.24 * ((k - 1) % 3);
      dx = 0.32 * floor((k - 1) / 3);
      init F{{k}}_CTB_N as battery {{ at = (31.6750 + dy, -103.7000 + dx); liq_cap = 24000 [bbl/d]; gas_cap = 17000 [Mscf/d]; }};
      init F{{k}}_CTB_C as battery {{ at = (31.6100 + dy, -103.6650 + dx); liq_cap = 30000 [bbl/d]; gas_cap = 19000 [Mscf/d]; }};
      init F{{k}}_CTB_S as battery {{ at = (31.5450 + dy, -103.7050 + dx); liq_cap = 20000 [bbl/d]; gas_cap = 16000 [Mscf/d]; oil_tank = 6000 [bbl]; }};
      for p in table("../kestrel/pads.csv") {{
        init F{{k}}_{{p.name}} as pad {{ at = (p.lat + dy, p.lon + dx); }};
        connect(F{{k}}_{{p.name}}.header, F{{k}}_{{p.home}}.feed) via flowline {{ cap_liquid = 14000 [bbl/d]; }};
        connect(F{{k}}_{{p.name}}.header, F{{k}}_{{p.alt}}.feed)  via flowline {{ cap_liquid = 9000 [bbl/d]; }};
      }}
      for w in table("../kestrel/wells.csv") {{
        init F{{k}}_{{w.name}} as esp_well {{ q_max = w.q_max; wc = w.wc; gor = w.gor; kw_rated = w.kw_rated;
                                         health = w.health; at = (w.lat + dy, w.lon + dx); }};
        connect(F{{k}}_{{w.name}}.prod, F{{k}}_{{w.pad}}.wells);
      }}
      init F{{k}}_CS1 as compressor_station {{ at = (31.6500 + dy, -103.6250 + dx); n_units = 3; unit_cap = 9000 [Mscf/d]; }};
      init F{{k}}_CS2 as compressor_station {{ at = (31.5700 + dy, -103.6300 + dx); n_units = 2; unit_cap = 8500 [Mscf/d]; }};
      init F{{k}}_FL1 as flare {{ at = (31.6510 + dy, -103.6230 + dx); }};
      init F{{k}}_FL2 as flare {{ at = (31.5710 + dy, -103.6280 + dx); }};
      connect(F{{k}}_CTB_N.gas_out, F{{k}}_CS1.suction) via flowline;
      connect(F{{k}}_CTB_C.gas_out, F{{k}}_CS1.suction) via flowline;
      connect(F{{k}}_CTB_C.gas_out, F{{k}}_CS2.suction) via flowline;
      connect(F{{k}}_CTB_S.gas_out, F{{k}}_CS2.suction) via flowline;
      connect(F{{k}}_CS1.discharge, GASPLANT.rec) via flowline;
      connect(F{{k}}_CS2.discharge, GASPLANT.rec) via flowline;
      connect(F{{k}}_CS1.flare, F{{k}}_FL1.burn);
      connect(F{{k}}_CS2.flare, F{{k}}_FL2.burn);
      init F{{k}}_FLEET as truck_fleet {{ at = (31.6000 + dy, -103.6000 + dx); n_trucks = 8; }};
      connect(F{{k}}_CTB_N.oil_out, LACT.rec) via flowline {{ cap_liquid = 9000 [bbl/d]; }};
      connect(F{{k}}_CTB_C.oil_out, LACT.rec) via flowline {{ cap_liquid = 5200 [bbl/d]; }};
      connect(F{{k}}_CTB_C.oil_out, LACT.rec) via truck_lane {{ distance = 16 [km]; }} as F{{k}}_LANE_C_OIL;
      connect(F{{k}}_CTB_S.oil_out, LACT.rec) via truck_lane {{ distance = 24 [km]; }} as F{{k}}_LANE_S_OIL;
      init F{{k}}_SWD1 as swd_well {{ at = (31.6900 + dy, -103.7600 + dx); inj_cap = 22000 [bbl/d]; }};
      init F{{k}}_SWD2 as swd_well {{ at = (31.6050 + dy, -103.7700 + dx); inj_cap = 24000 [bbl/d]; }};
      init F{{k}}_SWD3 as swd_well {{ at = (31.5300 + dy, -103.6400 + dx); inj_cap = 16000 [bbl/d]; }};
      connect(F{{k}}_CTB_N.wat_out, F{{k}}_SWD1.inj) via flowline;
      connect(F{{k}}_CTB_N.wat_out, F{{k}}_SWD2.inj) via flowline;
      connect(F{{k}}_CTB_C.wat_out, F{{k}}_SWD2.inj) via flowline;
      connect(F{{k}}_CTB_C.wat_out, F{{k}}_SWD3.inj) via flowline;
      connect(F{{k}}_CTB_S.wat_out, F{{k}}_SWD3.inj) via flowline;
      connect(F{{k}}_CTB_S.wat_out, F{{k}}_SWD1.inj) via truck_lane {{ distance = 21 [km]; cost_h = 85 [USD/h]; }} as F{{k}}_LANE_S_WTR;
      connect(F{{k}}_FLEET.pool, F{{k}}_LANE_C_OIL.fleet);
      connect(F{{k}}_FLEET.pool, F{{k}}_LANE_S_OIL.fleet);
      connect(F{{k}}_FLEET.pool, F{{k}}_LANE_S_WTR.fleet);
    }}
  behavior:
    constraint soft(500 [USD/Mscf]) flare_permit: sum(flare.burned) <= flare_permit;
    constraint soft(150 [USD/Mscf]) routine_flaring: sum(flare.burned) <= 0 [Mscf/d];
    metric total_oil = sum(esp_well.prod.oil) [bbl/d];
}};

define ops72 as sim {{
  env: enterprise; horizon = 72 [h]; step = 1 [h];
  objective: maximize sum(revenue) - sum(cost) - carbon_price * sum(emission);
  solver: partition = "pad"; route_hold = 24;
}};
'''


def enterprise_source(n: int) -> str:
    return TEMPLATE.format(N=n, permit=1500 * n, plant_cap=int(36000 * n))


def timeit(fn, reps=3):
    fn()
    t0 = time.perf_counter()
    for _ in range(reps):
        fn()
    return (time.perf_counter() - t0) / reps


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--fields", type=int, nargs="+", default=[1, 2, 4, 8])
    ap.add_argument("--no-solve", action="store_true")
    ap.add_argument("--ga", action="store_true", help="also run the best metaheuristic (GA) with the cascade's wall time")
    args = ap.parse_args()
    edir = os.path.join(ROOT, "scenarios", "enterprise")
    os.makedirs(edir, exist_ok=True)
    rows = []
    for n in args.fields:
        path = os.path.join(edir, f"enterprise_{n}.plx")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(enterprise_source(n))
        t0 = time.perf_counter()
        m = compile_model([path])
        t_compile = time.perf_counter() - t0
        prog = m.program
        pb = Problem(prog)
        sp = pb.space
        x1, x16 = sp.default_u(1), sp.default_u(16)
        t_sim1 = timeit(lambda: pb.evaluate(x1))
        t_sim16 = timeit(lambda: pb.evaluate(x16))

        def grad():
            x = x1.clone().requires_grad_(True)
            pb.evaluate(x).objective.sum().backward()
        t_grad = timeit(grad)
        summ = prog.summary()
        row = {"fields": n, "wells": 96 * n, "instances": summ["instances"], "edges": summ["edges"],
               "groups": summ["groups"], "decision_variables": sp.N, "discrete": int(sp.discrete_mask().sum()),
               "constraint_signals": summ["constraints"] * prog.T, "compile_s": t_compile,
               "simulate_ms_B1": t_sim1 * 1e3, "simulate_ms_B16": t_sim16 * 1e3, "gradient_ms": t_grad * 1e3,
               "generated_code_lines": summ["lines_of_generated_code"]}
        if not args.no_solve:
            t0 = time.perf_counter()
            res = Cascade(pb, config=CascadeConfig(use_neural=False)).solve()
            row.update({"solve_s": time.perf_counter() - t0, "objective": res.objective,
                        "max_violation": res.max_violation, "feasible": res.feasible,
                        "stages": res.stages})
            if args.ga:
                budget = row["solve_s"]
                r = MH.ga(lambda X: pb.fitness(X, mu=10.0, relax=False), sp.N, pop=48, iters=10 ** 6,
                          x0=sp.default_u(1), time_budget=budget)
                with torch.no_grad():
                    e = pb.evaluate(sp.round_discrete(r.best_x.view(1, -1)), relax=False)
                row.update({"ga_seconds": budget, "ga_objective": float(e.objective[0]),
                            "ga_max_violation": float(e.max_violation()[0])})
        rows.append(row)
        print(json.dumps({k: (round(v, 3) if isinstance(v, float) else v) for k, v in row.items() if k != "stages"}),
              flush=True)
        with open(os.path.join(ROOT, "bench", "results", "scaling.json"), "w") as fh:
            json.dump({"rows": rows}, fh, indent=1)


if __name__ == "__main__":
    main()
