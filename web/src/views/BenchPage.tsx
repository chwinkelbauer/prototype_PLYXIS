function Solvers({ sol }: { sol: any }) {
  const option = useMemo(() => {
    // five curves in fixed colour slots (PLYXIS first); every method is in the table below
    const shown = ["cascade+neural", "cascade", "ga", "de", "pso"];
    const series = shown.filter((n) => sol.curves?.[n]).map((name, i) => ({
      name, type: "line" as const, showSymbol: false, data: sol.curves[name],
      lineStyle: { width: i < 2 ? 2.2 : 1.6, color: SERIES[i] }, itemStyle: { color: SERIES[i] },
    }));
    return base({
      grid: { left: 78, right: 24, top: 30, bottom: 30 },
      xAxis: { type: "value", name: "seconds", axisLabel: { color: C.axis, fontSize: 10 }, splitLine: { show: false } },
      yAxis: { type: "value", scale: true, name: "penalised objective (72 h)", nameLocation: "middle", nameGap: 58, nameTextStyle: { color: C.axis, fontSize: 10 }, axisLabel: { color: C.axis, fontSize: 10, formatter: (v: number) => fmt.usd(v) }, splitLine: { lineStyle: { color: C.grid } } },
      series,
    });
  }, [sol]);
  return (
    <div className="col-span-6 panel">
      <div className="panel-h">Solver comparison on Kestrel ({fmt.n(sol.variables)} decisions, equal time budget)</div>
      <EChart height={250} option={option} />
      <table className="tbl">
        <thead><tr><th>method</th><th className="!text-right">best objective</th><th className="!text-right">max violation</th><th className="!text-right">time</th></tr></thead>
        <tbody>{(sol.table ?? []).map((r: any) => (
          <tr key={r.method}><td>{r.method}</td><td className="num text-right">{fmt.usd(r.objective)}</td>
            <td className={`num text-right ${r.max_violation > 0.005 ? "text-crit" : "text-good"}`}>{r.max_violation.toFixed(4)}</td>
            <td className="num text-right">{fmt.n(r.seconds, 1)} s</td></tr>))}</tbody>
      </table>
    </div>
  );
}

function Ablation({ abl }: { abl: any }) {
  const cases = abl.cases ?? [];
  const avg = (k: string) => cases.reduce((s: number, c: any) => s + c[k][0], 0) / Math.max(1, cases.length);
  return (
    <div className="col-span-12 panel">
      <div className="panel-h">Neural sub-solvers: re-planning after disruptions ({cases.length} held-out situations, trained on {abl.experts} cascade plans)</div>
      <table className="tbl">
        <thead><tr><th>case</th><th className="!text-right">reuse old plan + repair</th><th className="!text-right">neural + repair</th>
          <th className="!text-right">cascade</th><th className="!text-right">cascade + neural</th><th className="!text-right">neural inference</th></tr></thead>
        <tbody>
          {cases.map((c: any) => (
            <tr key={c.case}><td className="num">{c.case}</td>
              {["reuse_repair", "neural_repair", "cascade", "cascade_nn"].map((k) => (
                <td key={k} className={`num text-right ${c[k][1] > 0.005 ? "text-crit" : ""}`}>{fmt.usd(c[k][0])}{c[k][1] > 0.005 ? " ✗" : ""}</td>))}
              <td className="num text-right text-muted">{fmt.n(c.neural_ms)} ms</td></tr>
          ))}
          <tr className="font-semibold"><td>mean</td>{["reuse_repair", "neural_repair", "cascade", "cascade_nn"].map((k) => <td key={k} className="num text-right">{fmt.usd(avg(k))}</td>)}<td /></tr>
        </tbody>
      </table>
      <div className="px-3 py-2 text-[11.5px] text-dim">✗ = plan violates hard constraints by more than 0.5 %. Objective = profit minus carbon cost over the 72 h horizon.</div>
    </div>
  );
}

